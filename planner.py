import argparse
import csv
import json
import os
import tempfile
import webbrowser
from datetime import date, datetime, timedelta
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import scheduler

MEALS_FILE = "Meals.csv"
DISCOUNTS_FILE = "discounts.json"
DATA_FILE = "planner_data.js"
PLANNER_FILE = "planner.html"
REPORT_FILE = "nutrition_report.txt"

DEFAULT_PORT = 8765
SLOTS = ["Breakfast", "Lunch", "Snack", "Dinner"]

NUTRITION_FIELDS = {
    "Protein_g": "protein_g",
    "KCal": "kcal",
    "Fat_g": "fat_g",
    "Carbs_g": "carbs_g",
    "Iron_mg": "iron_mg",
    "Fiber_g": "fiber_g",
}


def to_float(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


# ------------------------------------------------------------------
# Data
# ------------------------------------------------------------------


def load_meals(filename):
    """
    Read Meals.csv and merge rows with the same title into one meal
    that can be used in several categories.
    """
    meals = {}
    with open(filename, "r", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            title = (row.get("TITLE") or "").strip()
            category = (row.get("CATEGORY") or "").strip()
            if not title or not category:
                continue

            if title not in meals:
                meals[title] = {
                    "title": title,
                    "hours": to_float(row.get("TOTAL_HOURS")) or 0.5,
                    "categories": [],
                    "ingredients": [
                        i.strip() for i in (row.get("Ingredients") or "").split(",") if i.strip()
                    ],
                    "nutrition": {
                        key: to_float(row.get(column)) for column, key in NUTRITION_FIELDS.items()
                    },
                }
            if category not in meals[title]["categories"]:
                meals[title]["categories"].append(category)

    return list(meals.values())


def load_discounts(filename):
    if not os.path.exists(filename):
        return None
    with open(filename, "r", encoding="utf-8") as f:
        return json.load(f)


def write_data_file(meals_file, discounts_file):
    meals = load_meals(meals_file)
    discounts = load_discounts(discounts_file)
    slot_times = {
        slot: scheduler.DEFAULT_MEAL_TIMES[slot][0].strftime("%H:%M") for slot in SLOTS
    }

    with open(DATA_FILE, "w", encoding="utf-8") as f:
        f.write("// Generated by planner.py - do not edit by hand.\n")
        f.write("window.PROTEEN_DATA = ")
        json.dump(
            {"meals": meals, "discounts": discounts, "slotTimes": slot_times},
            f, ensure_ascii=False,
        )
        f.write(";\n")

    return meals, discounts


# ------------------------------------------------------------------
# Saving a plan (same files and formats as scheduler.py)
# ------------------------------------------------------------------


def save_plan(plan, goals, meals_file, write_files=True):
    """
    plan:  [{"date": "2026-10-19", "slot": "Lunch", "title": "Chole Rice"}, ...]
    goals: {"protein_g": 80, ...}
    Writes meal_plan.ics, shopping_list.txt and nutrition_report.txt.
    With write_files=False nothing in the project is touched; only the report text is returned.
    """
    meals = {m["title"]: m for m in load_meals(meals_file)}
    nutrition_goals = dict(scheduler.DEFAULT_NUTRITION_GOALS)
    for key in nutrition_goals:
        if key in goals:
            nutrition_goals[key] = to_float(goals[key])

    by_day = {}
    for entry in plan:
        meal = meals.get(entry.get("title"))
        slot = entry.get("slot")
        if not meal or slot not in SLOTS:
            continue
        day = datetime.strptime(entry["date"], "%Y-%m-%d").date()
        by_day.setdefault(day, {})[slot] = meal

    if not by_day:
        raise ValueError("The plan is empty.")

    ics_content = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//MealScheduler//RandomMealGenerator//EN",
        "X-WR-CALNAME:Custom Meal Plan",
    ]
    ingredients = set()
    daily_totals = {}

    for day in sorted(by_day):
        totals = {key: 0.0 for key in scheduler.DEFAULT_NUTRITION_GOALS}
        previous_end = None

        for slot in SLOTS:
            meal = by_day[day].get(slot)
            if not meal:
                continue

            start_dt = datetime.combine(day, scheduler.DEFAULT_MEAL_TIMES[slot][0])
            if previous_end and start_dt < previous_end:
                start_dt = previous_end
            end_dt = start_dt + timedelta(hours=meal["hours"])
            previous_end = end_dt

            ics_content.append(
                scheduler.generate_ics_event(start_dt, end_dt, meal["title"], meal["nutrition"])
            )
            ingredients.update(meal["ingredients"])
            for key in totals:
                totals[key] += meal["nutrition"].get(key, 0.0)

        daily_totals[day] = totals

    result = {
        "files": [],
        "days": len(daily_totals),
        "meals": sum(len(v) for v in by_day.values()),
    }

    if not write_files:
        with tempfile.TemporaryDirectory() as tmp:
            report_path = scheduler.write_nutrition_report(
                daily_totals, nutrition_goals, os.path.join(tmp, REPORT_FILE)
            )
            with open(report_path, "r") as f:
                result["report"] = f.read()
        return result

    ics_content.append("END:VCALENDAR")
    with open(scheduler.OUTPUT_ICS_FILENAME, "w") as f:
        f.write("\n".join(ics_content))

    scheduler.write_shopping_list(ingredients, scheduler.OUTPUT_SHOPPING_LIST_FILENAME)
    scheduler.write_nutrition_report(daily_totals, nutrition_goals, REPORT_FILE)

    with open(REPORT_FILE, "r") as f:
        result["report"] = f.read()
    result["files"] = [scheduler.OUTPUT_ICS_FILENAME, scheduler.OUTPUT_SHOPPING_LIST_FILENAME, REPORT_FILE]
    return result


# ------------------------------------------------------------------
# Local server (127.0.0.1 only; serves the planner and saves plans)
# ------------------------------------------------------------------


def make_handler(meals_file, discounts_file):
    static_files = {
        "/": PLANNER_FILE,
        "/" + PLANNER_FILE: PLANNER_FILE,
        "/" + DATA_FILE: DATA_FILE,
    }

    class Handler(BaseHTTPRequestHandler):
        def send_body(self, status, body, content_type):
            data = body.encode("utf-8") if isinstance(body, str) else body
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(data)

        def send_json(self, status, payload):
            self.send_body(status, json.dumps(payload, ensure_ascii=False), "application/json; charset=utf-8")

        def do_GET(self):
            path = self.path.split("?", 1)[0]
            filename = static_files.get(path)
            if not filename:
                self.send_body(404, "Not found", "text/plain")
                return

            # Rebuild data on every load so Meals.csv / discounts.json edits show up on refresh
            if filename == DATA_FILE:
                write_data_file(meals_file, discounts_file)

            content_type = "text/html; charset=utf-8" if filename.endswith(".html") else "text/javascript; charset=utf-8"
            with open(filename, "rb") as f:
                self.send_body(200, f.read(), content_type)

        def do_POST(self):
            if self.path not in ("/api/save", "/api/report"):
                self.send_body(404, "Not found", "text/plain")
                return
            try:
                length = int(self.headers.get("Content-Length", 0))
                payload = json.loads(self.rfile.read(length).decode("utf-8"))
                write_files = self.path == "/api/save"
                result = save_plan(payload.get("plan", []), payload.get("goals", {}), meals_file, write_files)
                if write_files:
                    print(f"💾 Saved {result['meals']} meals over {result['days']} days -> {', '.join(result['files'])}")
                self.send_json(200, result)
            except Exception as e:
                self.send_json(400, {"error": str(e)})

        def log_message(self, format, *args):
            pass

    return Handler


# ------------------------------------------------------------------
# Main
# ------------------------------------------------------------------


def parse_arguments():
    parser = argparse.ArgumentParser(description="Run the interactive meal planner.")
    parser.add_argument("--meals", default=MEALS_FILE, help="Meals CSV file.")
    parser.add_argument("--discounts", default=DISCOUNTS_FILE, help="Discounts JSON from discounts.py.")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT, help="Local port (default: %(default)s).")
    parser.add_argument("--no-open", action="store_true", help="Don't open the planner in the browser.")
    parser.add_argument(
        "--static", action="store_true",
        help="Only write planner_data.js (open planner.html as a file; saving to the project is disabled).",
    )
    return parser.parse_args()


def main():
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    args = parse_arguments()

    meals, discounts = write_data_file(args.meals, args.discounts)
    offers = len(discounts["offers"]) if discounts else 0
    print(f"Loaded {len(meals)} meals, {offers} offers.")

    if args.static:
        print(f"Wrote {DATA_FILE}.")
        if not args.no_open:
            webbrowser.open("file://" + os.path.abspath(PLANNER_FILE))
        return

    server = ThreadingHTTPServer(("127.0.0.1", args.port), make_handler(args.meals, args.discounts))
    url = f"http://127.0.0.1:{args.port}/{PLANNER_FILE}"
    print(f"🍽️  Planner running at {url}  (Ctrl+C to stop)")
    if not args.no_open:
        webbrowser.open(url)

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")


if __name__ == "__main__":
    main()
